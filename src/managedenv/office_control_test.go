// Storage fixtures exercise repair publication and binding lifetime only. Real
// Office execution is separately checked in the opt-in candidate and Desktop.
func officeStoredFixture(t *testing.T, m *Manager, id, repairOf string) Manifest {
	t.Helper()
	spec, err := m.officeSpec()
	if err != nil {
		t.Fatal(err)
	}
	root := filepath.Join(m.root, "office", "instances", m.target, spec.OfficeBundle.Version, id)
	if err := os.MkdirAll(root, 0700); err != nil {
		t.Fatal(err)
	}
	entry := filepath.Join(root, "entry")
	if err := os.WriteFile(entry, []byte("verified fixture"), 0600); err != nil {
		t.Fatal(err)
	}
	launches := map[string]Launch{"python": {Executable: entry}}
	if strings.HasPrefix(m.target, "darwin-") {
		plist := filepath.Join(root, "dependencies/native/libreoffice/Contents/Info.plist")
		if err := os.MkdirAll(filepath.Dir(plist), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(plist, []byte(`<plist><dict><key>LSUIElement</key><true/></dict></plist>`), 0600); err != nil {
			t.Fatal(err)
		}
	}
	f := Manifest{SchemaVersion: SchemaVersion, Kind: "office", Key: id, InstanceID: id, Target: m.target, Source: "awaken-managed", Root: root, State: "ready", Spec: spec, RepairOf: repairOf, NodeLauncherVersion: 3, Executables: launches, Fingerprints: fingerprints(launches), CreatedAt: m.now()}
	if err := m.save(f); err != nil {
		t.Fatal(err)
	}
	return f
}

func TestOfficePythonCacheRefreshPreservesBindingAcrossRestart(t *testing.T) {
	opts := Options{Root: t.TempDir(), Catalog: officeCatalogForTest(t)}
	m := managerForTest(t, opts)
	f := officeStoredFixture(t, m, "old-cache", "")
	cache := filepath.Join(f.Root, "dependencies", "python", "lib", "__pycache__", "module.cpython-312.pyc")
	source := filepath.Join(f.Root, "dependencies", "python", "lib", "module.py")
	if err := os.MkdirAll(filepath.Dir(cache), 0700); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{cache, source} {
		if err := os.WriteFile(path, []byte("original"), 0600); err != nil {
			t.Fatal(err)
		}
		info, _ := os.Stat(path)
		f.Fingerprints[path] = fileIdentity(info)
	}
	if err := m.save(f); err != nil {
		t.Fatal(err)
	}
	owner := testOwner("persistent-office")
	original, err := m.bind(f, owner, false)
	if err != nil {
		t.Fatal(err)
	}
	next := officeStoredFixture(t, m, "new-current", "")
	if err := m.activateOfficeBundle(context.Background(), next); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(cache, []byte("regenerated bytecode"), 0600); err != nil {
		t.Fatal(err)
	}
	restarted := managerForTest(t, opts)
	got, err := restarted.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil || got.InstanceID != f.InstanceID || got.EnvironmentRef != original.EnvironmentRef || !got.Reused {
		t.Fatalf("cache refresh changed task binding: %+v %v", got, err)
	}
	if err := os.Remove(cache); err != nil {
		t.Fatal(err)
	}
	if _, err := restarted.EnsureOfficeBundle(context.Background(), owner, nil); err != nil {
		t.Fatal("removable bytecode cache made instance unhealthy", err)
	}
	if err := os.WriteFile(source, []byte("changed source must fail validation"), 0600); err != nil {
		t.Fatal(err)
	}
	oldExecution, err := os.ReadFile(filepath.Join(m.root, "bindings", owner.key(), original.EnvironmentRef+".execution.json"))
	if err != nil {
		t.Fatal(err)
	}
	got, err = restarted.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil || got.InstanceID != next.InstanceID || !got.Reused {
		t.Fatalf("failed automatic recovery: %+v %v", got, err)
	}
	if len(restarted.Operations()) != 0 {
		t.Fatal("healthy recovery instance reinstalled")
	}
	currentExecution, _ := os.ReadFile(filepath.Join(m.root, "bindings", owner.key(), original.EnvironmentRef+".execution.json"))
	if string(currentExecution) != string(oldExecution) {
		t.Fatal("recovery rewrote historical launch context")
	}
	// Restoring source files must not revive a superseded durable reference.
	if err := os.WriteFile(source, []byte("original"), 0600); err != nil {
		t.Fatal(err)
	}
	restarted = managerForTest(t, opts)
	_, err = restarted.RestoreBinding(context.Background(), original.EnvironmentRef, f.InstanceID, owner)
	assertEnvironmentCode(t, err, "environment_binding_stale")
	bindings := restarted.Bindings(owner)
	if len(bindings) != 1 || bindings[0].InstanceID != next.InstanceID {
		t.Fatalf("recovery projection: %+v", bindings)
	}
	if err := os.RemoveAll(f.Root); err != nil {
		t.Fatal(err)
	}
	got, err = restarted.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil || got.InstanceID != next.InstanceID {
		t.Fatalf("restart lost recovered binding: %+v %v", got, err)
	}
}
func TestOfficeRepairFailureAndWaiterCancellationPreserveCurrent(t *testing.T) {
	received, release := make(chan struct{}), make(chan struct{})
	var downloads atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if downloads.Add(1) == 1 {
			close(received)
		}
		select {
		case <-release:
			_, _ = w.Write([]byte("wrong checksum"))
		case <-r.Context().Done():
		}
	}))
	defer server.Close()
	defer close(release)
	catalog := officeCatalogForTest(t)
	asset := catalog.OfficeBundle.Assets[Target()]
	asset.URL = server.URL
	catalog.OfficeBundle.Assets[Target()] = asset
	m := managerForTest(t, Options{Root: t.TempDir(), Catalog: catalog, Client: server.Client(), AllowFileAssets: true})
	old := officeStoredFixture(t, m, "old", "")
	if err := m.activateOfficeBundle(context.Background(), old); err != nil {
		t.Fatal(err)
	}
	owner := testOwner("existing-task")
	binding, err := m.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil {
		t.Fatal(err)
	}
	first, cancel := context.WithCancel(context.Background())
	defer cancel()
	firstResult, secondResult := make(chan error, 1), make(chan error, 1)
	go func() {
		_, err := m.RepairOfficeBundle(first, old.InstanceID, testOwner("settings"), nil)
		firstResult <- err
	}()
	select {
	case <-received:
	case <-time.After(5 * time.Second):
		t.Fatal("repair reused healthy old copy instead of preparing a new one")
	}
	go func() {
		_, err := m.RepairOfficeBundle(context.Background(), old.InstanceID, testOwner("other-waiter"), nil)
		secondResult <- err
	}()
	spec, _ := m.officeSpec()
	key := digest([]any{m.target, spec})
	deadline := time.Now().Add(5 * time.Second)
	for {
		entries, _ := os.ReadDir(filepath.Join(m.root, "waiters", key))
		if len(entries) == 2 {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("second waiter not registered")
		}
		time.Sleep(10 * time.Millisecond)
	}
	cancel()
	if err = <-firstResult; !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	// Let the surviving waiter finish the same operation, without another fetch.
	release <- struct{}{}
	err = <-secondResult
	assertEnvironmentCode(t, err, "environment_checksum_mismatch")
	if downloads.Load() != 1 {
		t.Fatalf("duplicate downloads: %d", downloads.Load())
	}
	choice, _ := m.officeChoice()
	if choice.Current != old.InstanceID {
		t.Fatal("failure replaced old current")
	}
	if _, err = m.Binding(context.Background(), binding.EnvironmentRef, owner); err != nil {
		t.Fatal("existing binding damaged", err)
	}
	status, err := m.OfficeBundleStatus(context.Background())
	// The storage-only fixture has no executable runtime and must not pass the
	// new interpreter probes, even though its stored fingerprints are intact.
	if err != nil || status.State != "damaged" || !status.CanRepair || status.Operation == nil || status.Operation.State != "failed" {
		t.Fatalf("bad status: %+v %v", status, err)
	}
}

func TestOfficeRuntimeStatusChecksRowsIndependently(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("POSIX executable fixture; Windows compilation is checked separately")
	}
	m := managerForTest(t, Options{Root: t.TempDir(), Catalog: officeCatalogForTest(t)})
	f := officeStoredFixture(t, m, "runtime-status", "")
	for _, name := range []string{"python", "node"} {
		path := filepath.Join(f.Root, "dependencies", name, "bin", name)
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		prefix := "v"
		if name == "python" {
			prefix = "Python "
		}
		// This tests the status contract, not actual Python/Node package loading.
		body := "#!/bin/sh\nif [ \"$1\" = \"--version\" ]; then echo '" + prefix + f.Spec.ComponentVersions[name] + "'; else echo verified; fi\n"
		if err := os.WriteFile(path, []byte(body), 0700); err != nil {
			t.Fatal(err)
		}
		f.Executables[name] = Launch{Executable: path}
	}
	f.Fingerprints = fingerprints(f.Executables)
	if err := m.save(f); err != nil {
		t.Fatal(err)
	}
	if err := m.activateOfficeBundle(context.Background(), f); err != nil {
		t.Fatal(err)
	}
	status, err := m.OfficeBundleStatus(context.Background())
	if err != nil || status.State != "ready" || len(status.Runtimes) != 2 || status.Runtimes[0].State != "ready" || status.Runtimes[1].State != "ready" {
		t.Fatal(status, err)
	}
	asset := m.catalog.OfficeBundle.Assets[m.target]
	delete(m.catalog.OfficeBundle.Assets, m.target)
	status, err = m.OfficeBundleStatus(context.Background())
	if err != nil || status.State != "ready" || status.ErrorCode != "" {
		t.Fatal("installed status depends on download metadata", status, err)
	}
	changed := asset
	changed.SHA256 = digest("different archive")
	m.catalog.OfficeBundle.Assets[m.target] = changed
	status, err = m.OfficeBundleStatus(context.Background())
	if err != nil || status.State != "update_available" {
		t.Fatal("status ignored changed archive identity", status, err)
	}
	m.catalog.OfficeBundle.Assets[m.target] = asset
	if err := os.Remove(f.Executables["node"].Executable); err != nil {
		t.Fatal(err)
	}
	status, err = m.OfficeBundleStatus(context.Background())
	if err != nil || status.State != "damaged" || status.Runtimes[0].State != "ready" || status.Runtimes[1].State != "damaged" {
		t.Fatal("one broken runtime contaminated both rows", status, err)
	}
	if len(m.Operations()) != 0 || len(m.Bindings(testOwner("status"))) != 0 {
		t.Fatal("status prepared or bound an environment")
	}
}
func TestOfficeRepairResumesPublicationAndIsIdempotentAcrossManagers(t *testing.T) {
	c := officeCatalogForTest(t)
	root := t.TempDir()
	m := managerForTest(t, Options{Root: root, Catalog: c})
	old := officeStoredFixture(t, m, "old", "")
	if err := m.activateOfficeBundle(context.Background(), old); err != nil {
		t.Fatal(err)
	}
	owner := testOwner("original-task")
	oldBinding, err := m.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil {
		t.Fatal(err)
	}
	repaired := officeStoredFixture(t, m, "repaired", "old") // verified manifest survived a selection-commit interruption
	m2 := managerForTest(t, Options{Root: root, Catalog: c})
	done := make(chan Binding, 2)
	failures := make(chan error, 2)
	for i, manager := range []*Manager{m, m2} {
		go func(i int, manager *Manager) {
			b, e := manager.RepairOfficeBundle(context.Background(), "old", testOwner(string(rune('a'+i))), nil)
			done <- b
			failures <- e
		}(i, manager)
	}
	for i := 0; i < 2; i++ {
		if err := <-failures; err != nil {
			t.Fatal(err)
		}
		if b := <-done; b.InstanceID != repaired.InstanceID {
			t.Fatal("did not reuse completed repair", b.InstanceID)
		}
	}
	choice, _ := m.officeChoice()
	if choice.Current != "repaired" || choice.Previous != "old" {
		t.Fatal(choice)
	}
	pinned, err := m.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil || pinned.InstanceID != "old" || pinned.EnvironmentRef != oldBinding.EnvironmentRef {
		t.Fatal("repair rebound existing task", err)
	}
	fresh, err := m.EnsureOfficeBundle(context.Background(), testOwner("fresh"), nil)
	if err != nil || fresh.InstanceID != "repaired" {
		t.Fatal("new task did not use repair", err)
	}
}
