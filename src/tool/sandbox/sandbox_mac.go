//go:build darwin

package sandbox

import (
	"fmt"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
)

// sandboxExecPath is the canonical location of the sandbox-exec utility
// shipped with macOS. We check for it via exec.LookPath so that
// non-standard setups (e.g. a stripped-down macOS without the binary)
// degrade gracefully to SandboxDegraded.
const sandboxExecPath = "/usr/bin/sandbox-exec"

// SandboxAdapterMac is the macOS sandbox adapter. It wraps shell
// commands in `sandbox-exec -p <profile>` so that filesystem and
// network access are confined by a Seatbelt profile scoped to the
// workspace root.
//
// If sandbox-exec is not available on the system (checked via
// exec.LookPath at construction time), the adapter reports
// SandboxDegraded and applies no constraints. The ShellExecutor then
// fail-closes for open_world_system commands.
//
// SandboxAdapterMac is safe for concurrent use: its fields are
// immutable after construction.
type SandboxAdapterMac struct {
	// execPath is the resolved path to sandbox-exec. Empty when
	// sandbox-exec could not be found.
	execPath string

	// available is true when sandbox-exec was located via LookPath.
	available bool
}

// newSandboxAdapterMac constructs a SandboxAdapterMac, probing for
// sandbox-exec at construction time so SupportLevel() and
// ApplySandbox() can cheaply check availability without re-running
// LookPath on every call.
func newSandboxAdapterMac() SandboxAdapterMac {
	path, err := exec.LookPath(sandboxExecPath)
	if err != nil || path == "" {
		return SandboxAdapterMac{execPath: "", available: false}
	}
	// Presence alone is insufficient in hardened/containerized macOS
	// environments where Seatbelt invocation is blocked. Probe a no-op profile
	// once so SupportLevel never claims a boundary that cannot start.
	probe := exec.Command(path, "-p", "(version 1) (allow default)", "/usr/bin/true")
	if err := probe.Run(); err != nil {
		return SandboxAdapterMac{execPath: "", available: false}
	}
	return SandboxAdapterMac{execPath: path, available: true}
}

var (
	defaultMacAdapterOnce sync.Once
	defaultMacAdapter     SandboxAdapterMac
)

func defaultPlatformAdapter() SandboxAdapter {
	defaultMacAdapterOnce.Do(func() { defaultMacAdapter = newSandboxAdapterMac() })
	return defaultMacAdapter
}

// SupportLevel returns SandboxFull when sandbox-exec is available on
// the system, allowing open_world_system commands to run under
// confinement. When sandbox-exec is missing (non-standard macOS
// setup), it returns SandboxDegraded so the ShellExecutor fail-closes
// for open-world commands.
func (a SandboxAdapterMac) SupportLevel() SandboxSupport {
	if !a.available || a.execPath == "" {
		return SandboxDegraded
	}
	return SandboxFull
}

// ApplySandbox wraps cmd so it runs under `sandbox-exec -p <profile>`.
// The profile is generated by GenerateSandboxProfile based on the
// tier and workspaceRoot. cmd.Path and cmd.Args are mutated in place;
// the command is not started here.
//
// When sandbox-exec is unavailable, ApplySandbox is a no-op and
// returns a SandboxResult with Applied=false and Support=SandboxDegraded.
func (a SandboxAdapterMac) ApplySandbox(cmd *exec.Cmd, tier string, workspaceRoot string) (SandboxResult, error) {
	if !a.available || a.execPath == "" {
		return SandboxResult{
			Support: SandboxDegraded,
			Method:  "degraded",
			Applied: false,
		}, nil
	}

	root := workspaceRoot
	if strings.TrimSpace(root) == "" {
		// Fall back to cmd.Dir so the adapter still produces a usable
		// profile when the caller did not pass an explicit root.
		root = cmd.Dir
	}
	if root == "" {
		// Last-resort fallback: use the current working directory. This
		// keeps the profile valid but very restrictive.
		if wd, err := filepath.Abs("."); err == nil {
			root = wd
		}
	}

	// Resolve symlinks so the Seatbelt profile's subpath rules match
	// the real filesystem paths the kernel checks. macOS uses
	// /private/var for /var, /private/tmp for /tmp, etc. Without this,
	// a workspace root like /var/folders/... would not match the
	// resolved path /private/var/folders/... and the sandbox would
	// deny legitimate workspace writes.
	if resolved, err := filepath.EvalSymlinks(root); err == nil && resolved != "" {
		root = resolved
	}

	profile := GenerateSandboxProfile(tier, root)

	// Build the new arg list. cmd.Args[0] is conventionally the program
	// name; we preserve the original command and its args after the
	// sandbox-exec wrapper.
	originalPath := cmd.Path
	originalArgs := cmd.Args
	if len(originalArgs) == 0 {
		originalArgs = []string{originalPath}
	}

	newArgs := make([]string, 0, len(originalArgs)+4)
	newArgs = append(newArgs, "sandbox-exec", "-p", profile, originalPath)
	newArgs = append(newArgs, originalArgs[1:]...)

	cmd.Path = a.execPath
	cmd.Args = newArgs

	return SandboxResult{
		Support: SandboxFull,
		Method:  "sandbox-exec",
		Applied: true,
	}, nil
}

// GenerateSandboxProfile returns a Seatbelt sandbox profile (the
// language accepted by `sandbox-exec -p`) appropriate for the given
// tier and workspaceRoot.
//
// Profile strategy per tier:
//   - inspect_read_only: allow process execution and file reads; deny
//     all writes and network.
//   - local_cli: preserve normal macOS services and network while confining
//     file writes to the supplied root.
//   - workspace_mutation: allow process execution, file reads, and file
//     writes within the workspace; deny writes outside the workspace
//     and deny network.
//   - open_world_system: allow process execution, file reads, file
//     writes within the workspace, and network; deny writes outside
//     the workspace.
//
// `allow default` preserves Keychain/trustd/runtime services needed by local
// CLIs. The scoped deny uses `require-not (subpath ...)`: Seatbelt deny rules
// override broad allow rules, so an unconditional deny after an allow would
// incorrectly reject writes inside the root. Reads remain available; writes
// are confined to the root; network is denied for read-only/workspace tiers.
//
// For an unknown tier the profile is the most restrictive
// (inspect_read_only-style) as a safe default.
//
// workspaceRoot should be an absolute, real path. The supervising caller must
// reject a missing root before authorizing a write-capable command.
func GenerateSandboxProfile(tier string, workspaceRoot string) string {
	root := filepath.Clean(workspaceRoot)
	if root == "" || root == "." {
		// Callers requiring a write boundary reject an absent workspace before
		// applying this profile. Slash keeps the read-only fallback syntactically
		// valid without interpolating an empty Seatbelt literal.
		root = "/"
	}

	// Quote the path for the Seatbelt language. Seatbelt uses
	// double-quoted strings; we escape backslashes and double quotes.
	quoted := quoteSeatbeltString(root)

	switch tier {
	case TierInspectReadOnly:
		return fmt.Sprintf(`(version 1)
(allow default)
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow file-read* (subpath %s))
(allow file-read* (subpath "/"))
(deny file-write* (require-not (literal "/dev/null")))
(deny network*)
(deny appleevent-send)
`, quoted)

	case TierWorkspaceMutation:
		return fmt.Sprintf(`(version 1)
(allow default)
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow file-read* (subpath %s))
(allow file-read* (subpath "/"))
(allow file-write* (subpath %s))
(allow file-write* (literal "/dev/null"))
(deny file-write* (require-all (require-not (subpath %s)) (require-not (literal "/dev/null"))))
(deny network*)
(deny appleevent-send)
`, quoted, quoted, quoted)

	case TierLocalCLI:
		return fmt.Sprintf(`(version 1)
(allow default)
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow file-read* (subpath %s))
(allow file-read* (subpath "/"))
(allow file-write* (subpath %s))
(allow file-write* (literal "/dev/null"))
(deny file-write* (require-all (require-not (subpath %s)) (require-not (literal "/dev/null"))))
(allow network*)
(deny appleevent-send)
`, quoted, quoted, quoted)

	case TierOpenWorldSystem:
		return fmt.Sprintf(`(version 1)
(allow default)
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow file-read* (subpath %s))
(allow file-read* (subpath "/"))
(allow file-write* (subpath %s))
(allow file-write* (literal "/dev/null"))
(deny file-write* (require-all (require-not (subpath %s)) (require-not (literal "/dev/null"))))
(allow network*)
(deny appleevent-send)
`, quoted, quoted, quoted)

	default:
		// Conservative default: treat unknown tiers as read-only.
		return fmt.Sprintf(`(version 1)
(allow default)
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow file-read* (subpath %s))
(allow file-read* (subpath "/"))
(deny file-write* (require-not (literal "/dev/null")))
(deny network*)
(deny appleevent-send)
`, quoted)
	}
}

// quoteSeatbeltString returns the path wrapped in double quotes with
// any backslash or double-quote characters escaped, suitable for use
// as a literal string in a Seatbelt profile.
func quoteSeatbeltString(s string) string {
	escaped := strings.NewReplacer(
		`\`, `\\`,
		`"`, `\"`,
	).Replace(s)
	return `"` + escaped + `"`
}
