func TestOfficeMissingBoundInstanceRecoversWithoutReinstall(t *testing.T) {
	m := managerForTest(t, Options{Root: t.TempDir(), Catalog: officeCatalogForTest(t)})
	old := officeStoredFixture(t, m, "missing-bound", "")
	owner := testOwner("recovery")
	original, err := m.bind(old, owner, false)
	if err != nil {
		t.Fatal(err)
	}
	next := officeStoredFixture(t, m, "healthy-replacement", old.InstanceID)
	if err := m.activateOfficeBundle(context.Background(), next); err != nil {
		t.Fatal(err)
	}
	if err := os.RemoveAll(old.Root); err != nil {
		t.Fatal(err)
	}
	recovered, err := m.EnsureOfficeBundle(context.Background(), owner, nil)
	if err != nil || !recovered.Reused || recovered.InstanceID != next.InstanceID {
		t.Fatalf("missing instance did not recover: %+v %v", recovered, err)
	}
	if len(m.Operations()) != 0 {
		t.Fatal("existing replacement reinstalled")
	}
	_, err = m.Binding(context.Background(), original.EnvironmentRef, owner)
	assertEnvironmentCode(t, err, "environment_binding_stale")
	child := owner
	child.AgentID = "child"
	if err := m.Inherit(owner, child); err != nil {
		t.Fatal(err)
	}
	if bindings := m.Bindings(child); len(bindings) != 1 || bindings[0].InstanceID != next.InstanceID {
		t.Fatalf("child inherited obsolete binding: %+v", bindings)
	}
}

func TestAutomaticOfficeRecoveryFailurePreservesBindings(t *testing.T) {
	var downloads atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		downloads.Add(1)
		http.Error(w, "unavailable", http.StatusNotFound)
	}))
	defer server.Close()
	catalog := officeCatalogForTest(t)
	asset := catalog.OfficeBundle.Assets[Target()]
	asset.URL = server.URL
	catalog.OfficeBundle.Assets[Target()] = asset
	m := managerForTest(t, Options{Root: t.TempDir(), Catalog: catalog, Client: server.Client(), AllowFileAssets: true})
	old := officeStoredFixture(t, m, "damaged", "")
	if err := m.activateOfficeBundle(context.Background(), old); err != nil {
		t.Fatal(err)
	}
	owner := testOwner("failed-recovery")
	binding, err := m.bind(old, owner, false)
	if err != nil {
		t.Fatal(err)
	}
	other := officeStoredFixture(t, m, "other-task-version", "")
	other.Spec.OfficeBundle.Version = "unrelated-version"
	if err := m.save(other); err != nil {
		t.Fatal(err)
	}
	otherOwner := testOwner("unrelated")
	otherBinding, err := m.bind(other, otherOwner, false)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(m.root, "bindings", owner.key(), binding.EnvironmentRef+".json")
	before, _ := os.ReadFile(path)
	if err := os.Remove(old.Executables["python"].Executable); err != nil {
		t.Fatal(err)
	}
	_, err = m.EnsureOfficeBundle(context.Background(), owner, nil)
	if err == nil || downloads.Load() != 1 {
		t.Fatalf("recovery did not attempt normal preparation: %v downloads=%d", err, downloads.Load())
	}
	after, _ := os.ReadFile(path)
	if string(before) != string(after) {
		t.Fatal("failed preparation replaced old binding")
	}
	if _, err := m.Binding(context.Background(), otherBinding.EnvironmentRef, otherOwner); err != nil {
		t.Fatal("failed recovery affected unrelated task", err)
	}
}

func TestOfficeRepairAndAutomaticPreparationShareCancellationGroup(t *testing.T) {
	started, stopped := make(chan struct{}), make(chan struct{})
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		close(started)
		<-r.Context().Done()
		close(stopped)
	}))
	defer server.Close()
	catalog := officeCatalogForTest(t)
	asset := catalog.OfficeBundle.Assets[Target()]
	asset.URL = server.URL
	catalog.OfficeBundle.Assets[Target()] = asset
	m := managerForTest(t, Options{Root: t.TempDir(), Catalog: catalog, Client: server.Client(), AllowFileAssets: true})
	old := officeStoredFixture(t, m, "mixed-old", "")
	if err := m.activateOfficeBundle(context.Background(), old); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(old.Executables["python"].Executable); err != nil {
		t.Fatal(err)
	}
	repairCtx, cancelRepair := context.WithCancel(context.Background())
	defer cancelRepair()
	taskCtx, cancelTask := context.WithCancel(context.Background())
	defer cancelTask()
	repairDone, taskDone := make(chan error, 1), make(chan error, 1)
	go func() {
		_, err := m.RepairOfficeBundle(repairCtx, old.InstanceID, testOwner("settings-mixed"), nil)
		repairDone <- err
	}()
	select {
	case <-started:
	case <-time.After(5 * time.Second):
		t.Fatal("repair did not start")
	}
	go func() { _, err := m.EnsureOfficeBundle(taskCtx, testOwner("task-mixed"), nil); taskDone <- err }()
	spec, _ := m.officeSpec()
	group := digest([]any{m.target, spec})
	deadline := time.Now().Add(5 * time.Second)
	for {
		entries, _ := os.ReadDir(filepath.Join(m.root, "waiters", group))
		if len(entries) == 2 {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("mixed waiters did not share a group")
		}
		time.Sleep(10 * time.Millisecond)
	}
	cancelRepair()
	if err := <-repairDone; !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	select {
	case <-stopped:
		t.Fatal("canceling settings interrupted a task's preparation")
	case <-time.After(350 * time.Millisecond):
	}
	cancelTask()
	if err := <-taskDone; !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	select {
	case <-stopped:
	case <-time.After(5 * time.Second):
		t.Fatal("last cancellation did not stop work")
	}
}
