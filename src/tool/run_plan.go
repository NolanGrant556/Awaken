package tool

import (
	"context"
	"fmt"
	"strings"
	"time"
)

// RunPlanStatus is the stable three-state status of one run plan item
// (contract: [快照数据](docs/02_主智能体闭环/运行计划/实现方案.md#快照数据)).
type RunPlanStatus string

const (
	RunPlanPending    RunPlanStatus = "pending"
	RunPlanInProgress RunPlanStatus = "in_progress"
	RunPlanCompleted  RunPlanStatus = "completed"
)

// RunPlanItem is one ordered step of a run plan snapshot.
type RunPlanItem struct {
	Step       string        `json:"step"`
	ActiveForm string        `json:"active_form"`
	Status     RunPlanStatus `json:"status"`
}

// RunPlanSnapshot is the complete, self-sufficient plan snapshot for one root
// run. plan_id is generated by Core on the first successful update and never
// changes afterwards; version starts at 1 and increments strictly.
type RunPlanSnapshot struct {
	PlanID      string        `json:"plan_id"`
	Version     uint64        `json:"version"`
	Explanation string        `json:"explanation,omitempty"`
	Items       []RunPlanItem `json:"items"`
	UpdatedAt   time.Time     `json:"updated_at"`
}

// RunPlanUpdate is one whole-table replacement submitted through update_plan.
// BaseVersion implements optimistic concurrency: it must be 0 for the first
// update of a run and equal to the current version afterwards.
type RunPlanUpdate struct {
	Explanation string
	Items       []RunPlanItem
	BaseVersion uint64
}

// RunPlanResult is the sanitized outcome of one accepted update: the new
// snapshot plus derived counters consumed by the tool output schema.
type RunPlanResult struct {
	Snapshot       RunPlanSnapshot
	CompletedCount int
	TotalCount     int
	CurrentStep    int
	AllCompleted   bool
}

// Stable error codes carried by RunPlanError (contract [校验规则](docs/02_主智能体闭环/运行计划/实现方案.md#校验规则)/[异常、恢复与降级](docs/02_主智能体闭环/运行计划/实现方案.md#异常恢复与降级)).
const (
	RunPlanErrorInvalidInput       = "plan_invalid_input"
	RunPlanErrorVersionConflict    = "plan_version_conflict"
	RunPlanErrorPersistenceFailed  = "plan_persistence_failed"
	RunPlanErrorServiceUnavailable = "plan_service_unavailable"
)

// RunPlanError is the typed failure contract of RunPlanService. Code is
// stable for wire/tool outcome mapping. On a version conflict LatestVersion
// and LatestSnapshot carry the bounded current state so the model can retry
// against fresh truth.
type RunPlanError struct {
	Code           string
	Message        string
	Retryable      bool
	LatestVersion  uint64
	LatestSnapshot *RunPlanSnapshot
}

func (e *RunPlanError) Error() string {
	if e == nil {
		return ""
	}
	if strings.TrimSpace(e.Message) != "" {
		return fmt.Sprintf("%s: %s", e.Code, e.Message)
	}
	return e.Code
}

// RunPlanService is the narrow run-scoped plan contract consumed by the
// update_plan tool. Validation and journal-first persistence orchestration
// are the implementation's responsibility; the tool package must not import
// agentcore (import-cycle boundary, contract [快照数据](docs/02_主智能体闭环/运行计划/实现方案.md#快照数据)).
type RunPlanService interface {
	// ApplyUpdate validates and durably applies one whole-table update.
	// The host-owned identity supplies run/turn/tool-call identity; model
	// input never carries these fields.
	ApplyUpdate(ctx context.Context, identity ToolExecutionIdentity, update RunPlanUpdate) (RunPlanResult, error)
	// Snapshot returns the current in-memory snapshot, if any.
	Snapshot() (RunPlanSnapshot, bool)
	// ContextBlock renders the host-owned CurrentRunPlan text block for
	// later model boundaries. It returns an empty string when no plan exists.
	ContextBlock() (string, error)
}

type runPlanServiceContextKey struct{}

func ContextWithRunPlanService(ctx context.Context, service RunPlanService) context.Context {
	return context.WithValue(ctx, runPlanServiceContextKey{}, service)
}

func RunPlanServiceFromContext(ctx context.Context) (RunPlanService, bool) {
	if ctx == nil {
		return nil, false
	}
	service, ok := ctx.Value(runPlanServiceContextKey{}).(RunPlanService)
	return service, ok && service != nil
}
