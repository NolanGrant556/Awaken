package scheduledtask

import (
	"encoding/json"
	"fmt"
	"strings"
	"time"
	"unicode/utf8"
)

// Contract [校验](docs/12_定时任务/定时执行与提醒/实现方案.md#校验) limits. Core is the only validation owner; Renderer and
// templates pre-fill but never validate authoritatively.
const (
	MaxNameRunes                  = 120
	MaxContentBytes               = 32 * 1024
	MaxComposerTokens             = 24
	MaxComposerTokenMetadataBytes = 16 * 1024
	MinTimeoutSeconds             = 30
	MaxTimeoutSeconds             = 3600
	MaxMisfireGraceSec            = 86400
	MinRepeatCount                = 1
	MaxRepeatCount                = 10000
)

// ProjectChecker verifies that a project exists and is active. Injected by
// the caller so this package never depends on runtime/project packages.
type ProjectChecker func(projectID string) error

// ProfileChecker verifies that an explicitly selected model profile is
// ready. Injected by the caller for the same reason.
type ProfileChecker func(profileID string) error

// Validator validates task definitions. A nil Clock uses RealClock.
type Validator struct {
	CheckProject ProjectChecker
	CheckProfile ProfileChecker
	Clock        Clock
}

// ValidationError reports one invalid field. It intentionally carries only
// the field name and a static issue label: task content (prompts, reminder
// bodies) is user business data and must never leak into error strings.
type ValidationError struct {
	Field string
	Issue string
}

func (e *ValidationError) Error() string {
	return fmt.Sprintf("scheduledtask: invalid %s: %s", e.Field, e.Issue)
}

// Unwrap lets errors.Is(err, ErrValidationFailed) match.
func (e *ValidationError) Unwrap() error { return ErrValidationFailed }

func invalid(field, issue string) error {
	return &ValidationError{Field: field, Issue: issue}
}

func (v Validator) now() time.Time {
	if v.Clock != nil {
		return v.Clock.Now()
	}
	return time.Now()
}

// ValidateTask validates a full task definition. Client-supplied identity
// (task/thread/execution IDs, version, state, timestamps) is untrusted and
// regenerated by the repository at Create time, so it is not checked here.
func (v Validator) ValidateTask(task Task) error {
	if err := ValidateName(task.Name); err != nil {
		return err
	}
	if err := ValidateAction(task.Action); err != nil {
		return err
	}
	if err := v.ValidateSchedule(task.Schedule); err != nil {
		return err
	}
	if err := ValidateExecutionOptions(task.Execution); err != nil {
		return err
	}
	if v.CheckProject != nil {
		if err := v.CheckProject(task.ProjectID); err != nil {
			return invalid("project_id", "project is not active")
		}
	}
	if task.Execution.ProfileID != "" && v.CheckProfile != nil {
		if err := v.CheckProfile(task.Execution.ProfileID); err != nil {
			return invalid("execution.profile_id", "profile is not ready")
		}
	}
	return nil
}

// ValidateName enforces 1–120 Unicode characters (runes, not bytes).
func ValidateName(name string) error {
	runes := utf8.RuneCountInString(name)
	if runes < 1 || runes > MaxNameRunes {
		return invalid("name", "must be 1-120 characters")
	}
	return nil
}

// ValidateAction enforces a known kind and a prompt/body of at most 32 KiB.
// Reminder actions cannot carry Composer tokens. Agent actions may be
// token-only, matching the home Composer's structured selections.
func ValidateAction(action Action) error {
	switch action.Kind {
	case ActionKindReminder:
		if len(action.ComposerTokens) > 0 {
			return invalid("action.composer_tokens", "must be omitted for reminders")
		}
		if len(action.Content) == 0 {
			return invalid("action.content", "must not be empty")
		}
	case ActionKindAgent:
		if len(action.Content) == 0 && len(action.ComposerTokens) == 0 {
			return invalid("action.content", "must not be empty without composer tokens")
		}
	default:
		return invalid("action.kind", "must be reminder or agent")
	}
	if len(action.ComposerTokens) > MaxComposerTokens {
		return invalid("action.composer_tokens", "must contain at most 24 items")
	}
	promptBytes := len(action.Content)
	metadataBytes := 0
	seenTokenIDs := make(map[string]struct{}, len(action.ComposerTokens))
	for _, token := range action.ComposerTokens {
		tokenType := strings.ToLower(strings.TrimSpace(token.Type))
		if tokenType != "skill" && tokenType != "plugin" && tokenType != "rule" && tokenType != "command" && tokenType != "agent" && tokenType != "capability" {
			return invalid("action.composer_tokens", "must contain only skill, plugin, rule, command, agent, or capability tokens")
		}
		tokenID := strings.TrimSpace(token.ID)
		if tokenID == "" {
			return invalid("action.composer_tokens", "token identity is required")
		}
		if tokenType == "skill" && strings.TrimSpace(token.Payload.SkillID) == "" {
			return invalid("action.composer_tokens", "skill identity is required")
		}
		if (tokenType == "plugin" || tokenType == "rule" || tokenType == "command" || tokenType == "agent") && (strings.TrimSpace(token.Payload.PluginName) == "" || strings.TrimSpace(token.Payload.PluginDigest) == "") {
			return invalid("action.composer_tokens", "plugin identity is required")
		}
		if tokenType == "rule" && strings.TrimSpace(token.Payload.RuleLogicalID) == "" {
			return invalid("action.composer_tokens", "rule identity is required")
		}
		if tokenType == "command" {
			if strings.TrimSpace(token.Payload.CommandLogicalID) == "" {
				return invalid("action.composer_tokens", "command identity is required")
			}
			if encoded := strings.TrimSpace(token.Payload.CommandArgumentsJSON); encoded != "" {
				var arguments []string
				if json.Unmarshal([]byte(encoded), &arguments) != nil {
					return invalid("action.composer_tokens", "command arguments must be a JSON string array")
				}
			}
		}
		if tokenType == "agent" && strings.TrimSpace(token.Payload.AgentLogicalID) == "" {
			return invalid("action.composer_tokens", "agent identity is required")
		}
		if tokenType == "capability" && !strings.EqualFold(strings.TrimSpace(token.Payload.CapabilityID), "computer-use") {
			return invalid("action.composer_tokens", "unsupported capability identity")
		}
		if _, duplicate := seenTokenIDs[tokenID]; duplicate {
			return invalid("action.composer_tokens", "token IDs must be unique")
		}
		seenTokenIDs[tokenID] = struct{}{}
		promptBytes += len(token.LeadingText)
		metadataBytes += len(token.ID) + len(token.Type) + len(token.Label) +
			len(token.Payload.CapabilityID) + len(token.Payload.SkillID) + len(token.Payload.PluginName) + len(token.Payload.PluginDigest) +
			len(token.Payload.RuleLogicalID) + len(token.Payload.CommandLogicalID) + len(token.Payload.CommandArgumentsJSON) + len(token.Payload.AgentLogicalID) +
			len(token.Payload.SourceOrigin) +
			len(token.Payload.SkillFilePath) + len(token.Payload.RootDir)
	}
	if promptBytes > MaxContentBytes {
		return invalid("action.content", "must be at most 32 KiB")
	}
	if metadataBytes > MaxComposerTokenMetadataBytes {
		return invalid("action.composer_tokens", "metadata is too large")
	}
	return nil
}

// ValidateExecutionOptions enforces the timeout and misfire-grace ranges.
func ValidateExecutionOptions(opts ExecutionOptions) error {
	if opts.TimeoutSeconds < MinTimeoutSeconds || opts.TimeoutSeconds > MaxTimeoutSeconds {
		return invalid("execution.timeout_seconds", "must be 30-3600")
	}
	if opts.MisfireGraceSeconds < 0 || opts.MisfireGraceSeconds > MaxMisfireGraceSec {
		return invalid("execution.misfire_grace_seconds", "must be 0-86400")
	}
	return nil
}

// ValidateSchedule validates the schedule branch. Cron schedules must also
// produce a future occurrence from the validator clock; a calendar run_at in
// the past stays valid because the misfire rules ([misfire、时区和 DST](docs/12_定时任务/定时执行与提醒/实现方案.md#misfire时区和-dst)) define how it runs.
func (v Validator) ValidateSchedule(sched Schedule) error {
	if sched.Timezone == "" {
		return invalid("schedule.timezone", "must be a valid IANA timezone")
	}
	if _, err := time.LoadLocation(sched.Timezone); err != nil {
		return invalid("schedule.timezone", "must be a valid IANA timezone")
	}
	switch sched.Kind {
	case ScheduleKindCron:
		return v.validateCronSchedule(sched)
	case ScheduleKindCalendar:
		return validateCalendarSchedule(sched)
	default:
		return invalid("schedule.kind", "must be cron or calendar")
	}
}

func (v Validator) validateCronSchedule(sched Schedule) error {
	if cronFieldCount(sched.Cron) != 5 {
		return invalid("schedule.cron", "must have exactly 5 fields (minute hour day-of-month month day-of-week)")
	}
	if _, err := parseCron(sched.Cron); err != nil {
		return invalid("schedule.cron", "is not a valid five-field cron expression")
	}
	if _, ok := NextOccurrence(sched, v.now()); !ok {
		return invalid("schedule.cron", "has no future occurrence")
	}
	return nil
}

func validateCalendarSchedule(sched Schedule) error {
	if sched.RunAt == nil {
		return invalid("schedule.run_at", "is required for calendar schedules")
	}
	if sched.RepeatEveryDays < 0 {
		return invalid("schedule.repeat_every_days", "must be at least 1 when repeating")
	}
	if sched.RepeatEveryDays == 0 {
		if sched.RepeatEnd != nil {
			return invalid("schedule.repeat_end", "must be omitted for non-repeating schedules")
		}
		return nil
	}
	// Repeating: a nil RepeatEnd means never-ending.
	if sched.RepeatEnd == nil {
		return nil
	}
	switch sched.RepeatEnd.Kind {
	case RepeatEndNever:
		return nil
	case RepeatEndUntil:
		if sched.RepeatEnd.Until == nil {
			return invalid("schedule.repeat_end.until", "is required for until repeat end")
		}
		if !sched.RepeatEnd.Until.After(*sched.RunAt) {
			return invalid("schedule.repeat_end.until", "must be later than run_at")
		}
		return nil
	case RepeatEndCount:
		if sched.RepeatEnd.Count < MinRepeatCount || sched.RepeatEnd.Count > MaxRepeatCount {
			return invalid("schedule.repeat_end.count", "must be 1-10000")
		}
		return nil
	default:
		return invalid("schedule.repeat_end.kind", "must be never, until or count")
	}
}
