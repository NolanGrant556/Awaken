const BY_ID = new Map(AWAKEN_ICON_CATALOG.map((entry) => [entry.id, entry]));
const BY_CONCEPT = new Map(AWAKEN_ICON_CATALOG.map((entry) => [entry.concept, entry]));

export function getAwakenIcon(id: AwakenIconId): AwakenIconEntry {
  const entry = BY_ID.get(id);
  if (!entry) {
    throw new Error(`Unknown Awaken icon id: ${id}`);
  }
  return entry;
}

export function findAwakenIconByConcept(concept: string): AwakenIconEntry | undefined {
  return BY_CONCEPT.get(concept);
}

export function searchAwakenIcons(query: string): AwakenIconEntry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) {
    return [...AWAKEN_ICON_CATALOG];
  }
  return AWAKEN_ICON_CATALOG.filter((entry) => {
    const haystack = [entry.id, entry.name, entry.concept, ...entry.tags].join(" ").toLowerCase();
    return haystack.includes(needle);
  });
}

export function assertAwakenIconCatalog(): void {
  const ids = new Set<string>();
  const concepts = new Set<string>();
  for (const entry of AWAKEN_ICON_CATALOG) {
    if (ids.has(entry.id)) {
      throw new Error(`Duplicate icon id: ${entry.id}`);
    }
    if (concepts.has(entry.concept)) {
      throw new Error(`Duplicate icon concept: ${entry.concept}`);
    }
    ids.add(entry.id);
    concepts.add(entry.concept);
  }
  if (AWAKEN_ICON_CATALOG.length !== AWAKEN_ICON_IDS.length) {
    throw new Error(
      `Icon catalog size ${AWAKEN_ICON_CATALOG.length} does not match id list ${AWAKEN_ICON_IDS.length}`,
    );
  }
  for (const id of AWAKEN_ICON_IDS) {
    if (!ids.has(id)) {
      throw new Error(`Missing catalog entry for icon id: ${id}`);
    }
  }
}
